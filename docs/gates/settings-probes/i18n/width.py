"""Width in px of each stdin line with efontCN_12, and any glyph the font lacks.

Usage: python3 -I width.py <efont_cn12.c> < strings.txt
The font file is generated by the simulator build (firmware/sim/lib/efont_cn12/gen_font.py
writes firmware/sim/.pio/gen/efont/efont_cn12.c).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import efont  # noqa: E402

F = efont.Font(sys.argv[1])
for line in sys.stdin:
    s = line.rstrip("\n")
    if not s or s.startswith("#"):
        continue
    missing = [hex(ord(ch)) for ch in s if not F.has(ord(ch))]
    print(f"{F.width(s):4d}  {s}" + (f"   MISSING {missing}" if missing else ""))
