# PlatformIO pre-script for env:sim: copies the lgfx_efont_cn_12 array (efontCN_12, the
# device's only font) verbatim out of M5GFX's lgfx_efont_cn.c into
# .pio/gen/efont/efont_cn12.c, which the efont_cn12 library compiles.
#
# M5GFX is found at $CPA_M5GFX_DIR, else in firmware/app's libdeps (installed by
#   pio pkg install -d firmware/app -e cardputer-adv
# ). Its version must be the one firmware/app/platformio.ini pins, so the simulator
# draws the glyphs the device draws, and its lgfx_efont_cn.c must have the sha256 pinned
# below for that version. A new M5GFX pin needs its hash here, after the efont tests and
# firmware/sim/oracle/oracle.sh pass on it. The generated file is rebuilt when the
# source's hash or this script changes.
import hashlib
import json
import os
import re

Import("env")  # noqa: F821  (provided by SCons)

ARRAY = "lgfx_efont_cn_12"
REL_SRC = os.path.join("src", "lgfx", "Fonts", "efont", "lgfx_efont_cn.c")
SOURCE_SHA256 = {
    "0.2.33": "ceb7bae98279b5b196a4742b0814970d095ddcaabea8a9ac3cebe1e1f7add873",
}


def pinned_version(app_ini):
    with open(app_ini, encoding="utf-8") as f:
        m = re.search(r"m5stack/M5GFX@([0-9.]+)", f.read())
    if not m:
        raise SystemExit(f"gen_font: no m5stack/M5GFX@x.y.z pin in {app_ini}")
    return m.group(1)


def version_of(lib_dir):
    path = os.path.join(lib_dir, "library.json")
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f).get("version")


def find_m5gfx(app_dir, want):
    libdeps = os.path.join(app_dir, ".pio", "libdeps", "cardputer-adv")
    candidates = [os.environ.get("CPA_M5GFX_DIR", ""), os.path.join(libdeps, "M5GFX@" + want)]
    candidates.append(os.path.join(libdeps, "M5GFX"))
    seen = []
    for c in candidates:
        if not c:
            continue
        got = version_of(c)
        if got == want:
            return c
        seen.append(f"{c} ({got or 'missing'})")
    raise SystemExit(
        f"gen_font: M5GFX {want} not found; tried {', '.join(seen)}.\n"
        "  run: pio pkg install -d firmware/app -e cardputer-adv\n"
        "  or set CPA_M5GFX_DIR to an M5GFX " + want + " checkout"
    )


def extract_array(src_path):
    """The lines of `const uint8_t lgfx_efont_cn_12[N] = "..." ... ;`, unchanged."""
    out = []
    start = re.compile(r"^PROGMEM const uint8_t " + ARRAY + r"\[\d+\] =")
    with open(src_path, encoding="latin-1") as f:
        for line in f:
            if not out and not start.match(line):
                continue
            out.append(line if out else line.replace("PROGMEM ", "", 1))
            if line.rstrip().endswith(";"):
                return out
    raise SystemExit(f"gen_font: {ARRAY} not found in {src_path}")


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def checked_source(app_dir, want):
    src = os.path.join(find_m5gfx(app_dir, want), REL_SRC)
    got = sha256_of(src)
    if SOURCE_SHA256.get(want) != got:
        raise SystemExit(
            f"gen_font: {src} has sha256 {got}; gen_font.py pins {SOURCE_SHA256.get(want, 'nothing')} "
            f"for M5GFX {want}. Check the font with the efont tests and firmware/sim/oracle/oracle.sh, "
            "then pin the new hash in SOURCE_SHA256."
        )
    return src, got


def generate(project_dir):
    app_dir = os.path.normpath(os.path.join(project_dir, "..", "app"))
    want = pinned_version(os.path.join(app_dir, "platformio.ini"))
    src, src_sha = checked_source(app_dir, want)
    script_sha = sha256_of(os.path.join(project_dir, "lib", "efont_cn12", "gen_font.py"))
    out_dir = os.path.join(project_dir, ".pio", "gen", "efont")
    out = os.path.join(out_dir, "efont_cn12.c")
    stamp = f"// from M5GFX {want} {REL_SRC} sha256 {src_sha}, gen_font.py sha256 {script_sha}\n"
    if os.path.isfile(out):
        with open(out, encoding="latin-1") as f:
            if f.readline() == stamp:
                return
    os.makedirs(out_dir, exist_ok=True)
    body = extract_array(src)
    with open(out, "w", encoding="latin-1") as f:
        f.write(stamp)
        f.write("// Generated by firmware/sim/lib/efont_cn12/gen_font.py; efont licence: NOTICE.\n")
        f.write('#include "efont_cn12.h"\n')
        f.writelines(body)
    print(f"gen_font: {ARRAY} from M5GFX {want} -> {out}")


generate(env.subst("$PROJECT_DIR"))  # noqa: F821
