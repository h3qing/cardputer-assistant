#!/usr/bin/env python3
"""Mando for the Mac app (docs/24 §6): the firmware's committed sprites as Swift data, and the app icon.

Reads firmware/app/lib/theme/gen/{mando64_gen.h,mando46_gen.h,icons_gen.h} and tools/theme/mando_colours.json
(where they come from and their licence: NOTICE). Standard library only; never reads anything outside the repo.

  scripts/export_mando.py --swift Sources/CardputerUI/Theme/MandoSprites.swift
  scripts/export_mando.py --iconset build/AppIcon.iconset     # then: iconutil -c icns build/AppIcon.iconset
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import subprocess
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
GEN = REPO / "firmware/app/lib/theme/gen"
COLOURS = REPO / "tools/theme/mando_colours.json"

# (Swift name, header, frame label, width, height)
FRAMES = [
    ("review", "mando64_gen.h", "review 0", 36, 64),
    ("wait", "mando64_gen.h", "wait 0", 36, 64),
    ("think", "mando64_gen.h", "think 0", 36, 64),
    ("hop", "mando46_gen.h", "hop 6", 26, 46),
    ("doze", "mando46_gen.h", "doze", 26, 46),
]
BG_TOP, BG_BOTTOM, RIM, GLOW = 0x2C241E, 0x1A1512, 0x4A3E35, 0x6E4521


def frames(header: str) -> dict[str, bytes]:
    text = (GEN / header).read_text()
    found = re.findall(r"\{  // ([a-z]+(?: \d+)?)\n(.*?)\n    \}", text, re.S)
    return {label: bytes(int(h, 16) for h in re.findall(r"0x([0-9A-F]{2})", body)) for label, body in found}


def head() -> list[int]:
    text = (GEN / "icons_gen.h").read_text()
    body = re.search(r"kHead\[kHeadW \* kHeadH\] = \{(.*?)\};", text, re.S)
    assert body, "kHead not found"
    return [int(h, 16) for h in re.findall(r"0x([0-9A-F]{2})", body.group(1))]


def colours() -> list[int]:
    return [int(c[1:], 16) for c in json.loads(COLOURS.read_text())["colours"]]


def swift_source() -> str:
    lines = [
        "// Generated by mac/scripts/export_mando.py from firmware/app/lib/theme/gen/mando64_gen.h,",
        "// mando46_gen.h, icons_gen.h and tools/theme/mando_colours.json. Do not edit; regenerate.",
        "// Where Mando comes from and its licence: NOTICE. 4 bits a pixel, first pixel in the high nibble;",
        "// 0 is clear and n is colours[n - 1]. head: palette entries, 0x20 + n - 1 is colours[n - 1].",
        "",
        "enum MandoSprites {",
        "    static let colours: [UInt32] = [",
    ]
    lines += ["        " + ", ".join(f"0x{c:06X}" for c in colours()[i:i + 5]) + "," for i in range(0, 15, 5)]
    lines += ["    ]", ""]
    tables = {name: frames(name) for name in {f[1] for f in FRAMES}}
    for name, header, label, width, height in FRAMES:
        data = tables[header][label].hex().upper()
        assert len(data) == width * height, (name, len(data))
        lines.append(f"    static let {name} = MandoFrame(width: {width}, height: {height}, hex: \"\"\"")
        lines += ["        " + data[i:i + 96] for i in range(0, len(data), 96)]
        lines += ["        \"\"\")", ""]
    pixels = head()
    lines.append("    static let head: [UInt8] = [")
    lines += ["        " + ", ".join(f"0x{p:02X}" for p in pixels[i:i + 11]) + "," for i in range(0, len(pixels), 11)]
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def png(path: Path, width: int, height: int, rgba: bytearray) -> None:
    rows = b"".join(b"\x00" + bytes(rgba[y * width * 4:(y + 1) * width * 4]) for y in range(height))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows, 9))
                     + chunk(b"IEND", b""))


def rgb(value: int) -> tuple[int, int, int]:
    return (value >> 16) & 0xFF, (value >> 8) & 0xFF, value & 0xFF


def mix(a: tuple[int, ...], b: tuple[int, ...], t: float) -> tuple[int, ...]:
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def coverage(x: int, y: int, box: tuple[int, int, int, int], radius: int) -> float:
    """How much of pixel (x, y) a rounded rectangle covers, 4 x 4 samples near the corners."""
    left, top, right, bottom = box
    inside = 0
    for sy in range(4):
        for sx in range(4):
            px, py = x + (sx + 0.5) / 4, y + (sy + 0.5) / 4
            cx = min(max(px, left + radius), right - radius)
            cy = min(max(py, top + radius), bottom - radius)
            inside += (px - cx) ** 2 + (py - cy) ** 2 <= radius ** 2 and left <= px <= right and top <= py <= bottom
    return inside / 16


def icon_1024() -> bytearray:
    size, box, radius = 1024, (100, 100, 924, 924), 185
    out = bytearray(size * size * 4)
    sprite, (sw, sh), scale = frames("mando64_gen.h")["review 0"], (36, 64), 11
    palette = [rgb(c) for c in colours()]
    ox, oy = (size - sw * scale) // 2, box[3] - 56 - sh * scale
    for y in range(size):
        for x in range(size):
            near_corner = (x < box[0] + radius or x > box[2] - radius) and (y < box[1] + radius or y > box[3] - radius)
            inside = float(box[0] <= x < box[2] and box[1] <= y < box[3])
            cover = coverage(x, y, box, radius) if near_corner else inside
            if cover == 0:
                continue
            colour = mix(rgb(BG_TOP), rgb(BG_BOTTOM), (y - box[1]) / (box[3] - box[1]))
            glow = max(0.0, 1 - ((x - 512) ** 2 + ((y - 520) * 1.2) ** 2) ** 0.5 / 380) ** 1.6
            colour = mix(colour, rgb(GLOW), 0.55 * glow)
            colour = rgb(RIM) if box[1] <= y < box[1] + 6 else colour
            sx, sy = (x - ox) // scale, (y - oy) // scale
            if 0 <= sx < sw and 0 <= sy < sh:
                byte = sprite[(sy * sw + sx) // 2]
                n = byte >> 4 if sx % 2 == 0 else byte & 0x0F
                colour = palette[n - 1] if n else colour
            out[(y * size + x) * 4:(y * size + x) * 4 + 4] = bytes((*colour, round(255 * cover)))
    return out


def iconset(directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    big = directory / "icon_512x512@2x.png"
    png(big, 1024, 1024, icon_1024())
    for points in (16, 32, 128, 256, 512):
        for factor in (1, 2):
            name = f"icon_{points}x{points}" + ("@2x" if factor == 2 else "") + ".png"
            pixels = points * factor
            if pixels != 1024:
                subprocess.run(["sips", "-z", str(pixels), str(pixels), str(big), "--out", str(directory / name)],
                               check=True, capture_output=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--swift", type=Path)
    parser.add_argument("--iconset", type=Path)
    args = parser.parse_args()
    if args.swift:
        args.swift.write_text(swift_source())
    if args.iconset:
        iconset(args.iconset)


if __name__ == "__main__":
    main()
