"""Hand-pixelled pictures (docs/19 §5.1): the status bar's 11 x 9 Mando head, drawn in
Mando's own colours (m1..m15, from mando_colours.json) and OnAccent. Each pixel becomes a
palette entry; 0 (a sentinel, never drawn) is clear. Writes lib/theme/gen/icons_gen.h.
"""

from __future__ import annotations

import tokens as tk

# The companion mockups' status bar head (scratchpad/visual/companion/src/lib.py HEAD).
HEAD = [
    ".k.......k.",
    "kek.....kek",
    "kpck...kcpk",
    "kcccccccccc",
    "kcEcccccEck",
    ".cccwwwccc.",
    ".kccwnwcck.",
    "..kcwwwck..",
    "...kkkkk...",
]
# Pixel -> m<n> (Mando colour n) or a token name; "." is clear.
HEAD_KEY = {"k": "m13", "e": "m5", "p": "m3", "c": "m6", "E": "OnAccent", "w": "m1", "n": "OnAccent"}


def entry_of(name: str) -> int:
    if name.startswith("m"):
        n = int(name[1:])
        if not 1 <= n <= 15:
            raise ValueError(f"no Mando colour {name}")
        return tk.MANDO_BASE + n - 1
    return tk.token_index(tk.token_names().index(name))


def pixels(art: list[str], key: dict[str, str]) -> list[int]:
    width = len(art[0])
    if any(len(row) != width for row in art):
        raise ValueError("ragged art")
    return [0 if ch == "." else entry_of(key[ch]) for row in art for ch in row]


def header() -> str:
    px = pixels(HEAD, HEAD_KEY)
    w = len(HEAD[0])
    rows = ["    " + ", ".join(f"0x{v:02X}" for v in px[i : i + w]) + "," for i in range(0, len(px), w)]
    lines = [
        "// Generated by tools/theme/gen_all.py (gen_icons.py). Do not edit; regenerate.",
        "// Palette entries per pixel, 0 = clear. Mando's colours: WhisperWoof (MIT, NOTICE).",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace cpa {",
        "namespace theme {",
        "namespace gen {",
        "",
        f"constexpr int16_t kHeadW = {w};",
        f"constexpr int16_t kHeadH = {len(HEAD)};",
        "constexpr uint8_t kHead[kHeadW * kHeadH] = {",
        *rows,
        "};",
        "",
        "}  // namespace gen",
        "}  // namespace theme",
        "}  // namespace cpa",
        "",
    ]
    return "\n".join(lines)
