"""The big digits (docs/19 §2.4): Nunito ExtraBold (weight 800, SIL OFL 1.1) from WhisperWoof's
font file (read only), 30 px for the recording timers and 34 px for the lock clock. Only 0-9
and ":" are baked. Nunito's figures are tabular, so each digit sits in a cell of the font's own
advance and a running timer never shifts; the rows are the digits' ink rows. Coverage is cut
to 6 levels (0 clear, 5 the ink), drawn through a palette ramp, as the companion mockups did.
Writes lib/theme/gen/digits_gen.h, 4 bits a pixel, high nibble first.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import gen_mando

FONT = Path("src") / "assets" / "fonts" / "Nunito-normal-latin.woff2"
WEIGHT = 800
LEVELS = 6
GLYPHS = "0123456789:"
FACES = (("Timer", 30), ("Clock", 34))
MARGIN = 8  # room left and right of a glyph while rendering, to see ink outside its cell


@dataclass
class Face:
    name: str
    size: int
    cell: int  # a digit's advance
    colon: int  # the colon's advance
    h: int  # ink rows shared by every glyph
    glyphs: dict[str, list[list[int]]] = field(default_factory=dict)  # levels, rows of cell (colon) px


def level_of(v: int) -> int:
    """Coverage 0-255 -> level 0-5, rounded like the mockup (never a tie)."""
    return round(v * (LEVELS - 1) / 255)


def font_path(whisperwoof: Path) -> Path:
    return whisperwoof / FONT


def render_face(path: Path, name: str, size: int) -> Face:
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(str(path), size)
    font.set_variation_by_axes([WEIGHT])
    asc, desc = font.getmetrics()
    images, advances = {}, {}
    for ch in GLYPHS:
        adv = font.getlength(ch)
        if adv != int(adv):
            raise ValueError(f"{ch!r} advances {adv} px: not a whole pixel")
        im = Image.new("L", (int(adv) + 2 * MARGIN, asc + desc), 0)
        ImageDraw.Draw(im).text((MARGIN, 0), ch, font=font, fill=255)
        box = im.getbbox()
        if box[0] < MARGIN or box[2] > MARGIN + adv:
            raise ValueError(f"{ch!r} inks outside its {adv} px cell")
        images[ch], advances[ch] = im, int(adv)
    if len({advances[d] for d in "0123456789"}) != 1:
        raise ValueError("the figures are not tabular")
    top = min(im.getbbox()[1] for im in images.values())
    bottom = max(im.getbbox()[3] for im in images.values())
    face = Face(name, size, advances["0"], advances[":"], bottom - top)
    for ch, im in images.items():
        px = im.load()
        face.glyphs[ch] = [[level_of(px[MARGIN + x, y]) for x in range(advances[ch])] for y in range(top, bottom)]
    return face


def build(whisperwoof: Path) -> list[Face]:
    return [render_face(font_path(whisperwoof), name, size) for name, size in FACES]


def _bytes(data: bytes, indent: str) -> list[str]:
    per = gen_mando.BYTES_PER_LINE
    return [indent + ",".join(f"0x{v:02X}" for v in data[i : i + per]) + "," for i in range(0, len(data), per)]


def _face_lines(f: Face) -> list[str]:
    n = (f.cell * f.h + 1) // 2
    lines = [
        f"// {f.name}: Nunito 800 at {f.size} px.",
        f"constexpr int16_t k{f.name}Cell = {f.cell};",
        f"constexpr int16_t k{f.name}Colon = {f.colon};",
        f"constexpr int16_t k{f.name}H = {f.h};",
        f"constexpr uint8_t k{f.name}Digits[10][{n}] = {{",
    ]
    for d in "0123456789":
        lines += [f"    {{  // {d}", *_bytes(gen_mando.pack4(f.glyphs[d]), "        "), "    },"]
    lines += [
        "};",
        f"constexpr uint8_t k{f.name}ColonPx[{(f.colon * f.h + 1) // 2}] = {{",
        *_bytes(gen_mando.pack4(f.glyphs[":"]), "    "),
        "};",
        "",
    ]
    return lines


def header(faces: list[Face], font_sha: str, pillow: str) -> str:
    lines = [
        "// Generated by tools/theme/gen_all.py (gen_digits.py). Do not edit; regenerate.",
        "// Nunito ExtraBold, Copyright 2014 The Nunito Project Authors, SIL OFL 1.1 (NOTICE,",
        f"// LICENSES/OFL-1.1.txt), from WhisperWoof with Pillow {pillow}:",
        f"//   {FONT.as_posix()} {font_sha[:16]}",
        "// 0-9 and ':' only. Each glyph is cell x H levels 0-5 (0 clear, 5 the ink), 4 bits a",
        "// pixel, row-major, the first pixel in the high nibble. Only theme_digits.cpp includes this.",
        *gen_mando.GUARD_OPEN,
        *gen_mando.NAMESPACE_OPEN,
    ]
    for f in faces:
        lines += _face_lines(f)
    return "\n".join([*lines, *gen_mando.NAMESPACE_CLOSE])
