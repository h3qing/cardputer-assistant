// The M5GFX oracle (oracle.sh): FbCanvas against M5GFX's own sprite, pixel for pixel.
//   oracle            every case of oracle_cases.h, on a fresh and on a shared sprite;
//                     exit 1 if any pixel or width differs
//   oracle --golden   test/test_efont/oracle_golden.h on stdout, from M5GFX alone
#include <cstdint>
#include <cstdio>
#include <cstring>

#include "oracle_cases.h"
#include "theme_palette.h"

int m5gfx_render(int i, uint8_t* out, bool fresh);
int m5gfx_glyph(int i, uint8_t* out);
int fbcanvas_render(int i, uint8_t* out, bool fresh);

namespace {

constexpr int kW = 240;
constexpr int kH = 135;
uint8_t g_dev[kW * kH];
uint8_t g_sim[kW * kH];

const char* label(const oracle::Case& c) { return c.fill ? "(fill)" : c.text; }

// The cases that differ.
int compare(bool fresh) {
  int bad = 0;
  for (int i = 0; i < oracle::kCaseCount; ++i) {
    const int wd = m5gfx_render(i, g_dev, fresh);
    const int ws = fbcanvas_render(i, g_sim, fresh);
    int diff = 0;
    int first = -1;
    for (int p = 0; p < kW * kH; ++p) {
      if (g_dev[p] == g_sim[p]) continue;
      first = first < 0 ? p : first;
      ++diff;
    }
    bad += (diff || wd != ws) ? 1 : 0;
    std::printf("%s case %2d: %5d px differ, width m5gfx %d sim %d  %s\n", fresh ? "fresh " : "shared", i, diff, wd,
                ws, label(oracle::kCases[i]));
    if (first >= 0) {
      std::printf("          first at (%d,%d): m5gfx 0x%02X sim 0x%02X\n", first % kW, first / kW, g_dev[first],
                  g_sim[first]);
    }
  }
  return bad;
}

void golden_glyph(int i) {
  const int w = m5gfx_glyph(i, g_dev);
  for (int y = 0; y < oracle::kGlyphRows; ++y) {
    std::printf("%s\"", y == 0 ? "    {" : "     ");
    const uint8_t ink = cpa::theme::index_of(cpa::Color::Fg).value();
    for (int x = 0; x < w; ++x) std::printf("%c", g_dev[y * kW + x] == ink ? '#' : '.');
    std::printf("\"%s", y + 1 < oracle::kGlyphRows ? "," : "},");
    std::printf(y == 0 ? "  // %s\n" : "\n", oracle::kGlyphs[i]);
  }
}

void golden() {
  std::printf(
      "// Generated by firmware/sim/oracle/oracle.sh --golden from M5GFX %s's own LGFX_Sprite:\n"
      "// what it draws for each case of oracle_cases.h (FNV-1a of the 240 x 135 bytes, and\n"
      "// textWidth), and the rows of kGlyphs ('#' ink). Do not edit; regenerate.\n"
      "#pragma once\n\n#include <cstdint>\n\n#include \"oracle_cases.h\"\n\nnamespace oracle {\n\n"
      "struct Golden {\n  uint64_t hash;\n  int width;\n};\n\nconstexpr Golden kGolden[] = {\n",
      ORACLE_M5GFX_VERSION);
  for (int i = 0; i < oracle::kCaseCount; ++i) {
    const int w = m5gfx_render(i, g_dev, true);
    std::printf("    {0x%016llXull, %d},  // %d\n", static_cast<unsigned long long>(oracle::fnv1a(g_dev, kW * kH)), w,
                i);
  }
  std::printf("};\nstatic_assert(sizeof(kGolden) / sizeof(kGolden[0]) == kCaseCount, \"regenerate\");\n\n");
  std::printf("constexpr const char* kGlyphRowsGolden[][kGlyphRows] = {\n");
  for (int i = 0; i < oracle::kGlyphCount; ++i) golden_glyph(i);
  std::printf("};\n\n}  // namespace oracle\n");
}

}  // namespace

int main(int argc, char** argv) {
  if (argc == 2 && std::strcmp(argv[1], "--golden") == 0) {
    golden();
    return 0;
  }
  const int bad = compare(true) + compare(false);
  std::printf("%d case(s) differ\n", bad);
  return bad ? 1 : 0;
}
